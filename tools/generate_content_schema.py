#!/usr/bin/env python3
"""Generate the Rust resource identifier schema from public extraction metadata."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def generate():
    manifest = json.loads((ROOT / 'web/content-manifest.json').read_text())
    identifiers = [entry['id'] for entry in manifest['entries']]
    if identifiers != sorted(set(identifiers)) or not all(0 < i < 2**32 for i in identifiers):
        raise ValueError('Resource IDs must be positive, unique and sorted')
    rows = [', '.join(map(str, identifiers[i:i + 12])) + ',' for i in range(0, len(identifiers), 12)]
    widths = {'f32': 4, 'f64': 8, 'i32': 4}
    binary = [(e['id'], widths[e['encoding']]) for e in manifest['entries'] if 'encoding' in e]
    return ('// @generated by tools/generate_content_schema.py; no resource payloads.\n'
            'pub const REQUIRED_IDS: &[u32] = &[\n' + '\n'.join('    ' + row for row in rows) + '\n];\n'
            + 'pub const BINARY_LENGTHS: &[(u32, usize)] = &[\n'
            + ''.join(f'    ({identifier}, {width}),\n' for identifier, width in binary) + '];\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'engine/wsr-core/src/content_ids.rs'
    generated = generate()
    if args.check:
        if path.read_text() != generated:
            parser.error('Resource schema is stale; run tools/generate_content_schema.py')
        print('Resource schema is current.')
    else:
        path.write_text(generated)
