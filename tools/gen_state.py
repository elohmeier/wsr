#!/usr/bin/env python3
"""Generate engine/wsr-core/src/state.rs: the game's global state as one Rust struct.

Inputs: tools/names.tsv (names, descriptions), decompiled/globals.tsv (DIM bounds/types),
decompiled/types.tsv (scalar types from tools/pbtypes.py). Re-run after renaming globals.

Usage: tools/gen_state.py
"""
import keyword
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RUST = {'INTEGER': 'Integer', 'LONG': 'Long', 'QUAD': 'Quad', 'SINGLE': 'Single', 'DOUBLE': 'Double',
        'EXT': 'Ext', 'CUR': 'Cur', 'CUX': 'Cux', 'STRING': 'PbStr', 'BYTE': 'u8'}
SIZE = {'INTEGER': 2, 'LONG': 4, 'QUAD': 8, 'SINGLE': 4, 'DOUBLE': 8, 'EXT': 10, 'CUR': 8, 'CUX': 8,
        'STRING': 4, 'BYTE': 1}
RUST_KW = {'type', 'match', 'loop', 'move', 'ref', 'self', 'super', 'crate', 'mod', 'fn', 'impl', 'trait', 'use',
           'where', 'async', 'await', 'dyn', 'box', 'yield', 'priv', 'final', 'macro', 'override', 'virtual'}


def snake(n):
    s = re.sub(r'(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])', '_', n).lower()
    s = re.sub(r'_+', '_', s).strip('_')
    return s + '_' if s in RUST_KW or keyword.iskeyword(s) else s


def tsv(p):
    rows = []
    for ln in open(os.path.join(ROOT, p)):
        if ln.startswith('#') or ln.startswith('addr\t'):
            continue
        rows.append(ln.rstrip('\n').split('\t'))
    return rows


def main():
    names = {r[0]: r for r in tsv('tools/names.tsv') if re.match(r'^6c[0-9a-f]{4}$', r[0])}
    dims = {r[0]: r[3] for r in tsv('decompiled/globals.tsv') if len(r) > 3 and r[3]}
    types = {r[0]: r[1] for r in tsv('decompiled/types.tsv')}
    fields, skipped, end = [], [], 0
    for a in sorted(names, key=lambda x: int(x, 16)):
        addr = int(a, 16)
        name, desc = names[a][1], (names[a][3] if len(names[a]) > 3 else '')
        if a in dims:
            m = re.match(r'^\((.*)\) AS (\w+)$', dims[a])
            bounds = [tuple(int(v) for v in b.split(' TO ')) for b in m.group(1).split(', ')]
            fields.append(('array', a, name, m.group(2), bounds, desc))
            end = max(end, addr + 0x74)
            continue
        t = types.get(a, 'LONG')
        if addr < end:      # high half of a wider value at a lower address (e.g. *_Hi of a QUAD)
            skipped.append((a, name))
            continue
        end = addr + SIZE.get(t, 4)
        fields.append(('scalar', a, name, t, None, desc))
    out = ['// @generated by tools/gen_state.py from tools/names.tsv and the decompiled inventories. Do not edit.',
           '//! Global game state of WSR.EXE: every global variable and array, with its original address,',
           '//! PowerBASIC type and `DIM` bounds. Field docs are the proposed descriptions from `tools/names.tsv`.',
           '',
           '#![allow(clippy::too_many_lines)]',
           '',
           'use crate::pb::array::{Arr1, Arr2};',
           'use crate::pb::pbstr::PbStr;',
           'use crate::pb::types::*;',
           '',
           '/// All globals of the original program.',
           '#[derive(Clone, Debug)]',
           'pub struct Globals {']
    init = []
    for kind, a, name, t, bounds, desc in fields:
        f = snake(name)
        doc = desc.replace('*/', '* /').strip() or name
        out.append('    /// %s' % doc)
        if kind == 'array':
            dimtxt = ', '.join('%d TO %d' % b for b in bounds)
            out.append('    ///')
            out.append('    /// `DIM %s(%s) AS %s` at 0x%s.' % (name, dimtxt, t, a))
            if len(bounds) == 1:
                out.append('    pub %s: Arr1<%s>,' % (f, RUST[t]))
                init.append('            %s: Arr1::new(%d, %d),' % (f, *bounds[0]))
            else:
                out.append('    pub %s: Arr2<%s>,' % (f, RUST[t]))
                init.append('            %s: Arr2::new(%d, %d, %d, %d),' % (f, *bounds[0], *bounds[1]))
        else:
            out.append('    ///')
            out.append('    /// `%s AS %s` at 0x%s.' % (name, t, a))
            out.append('    pub %s: %s,' % (f, RUST[t]))
            init.append('            %s: Default::default(),' % f)
    out.append('}')
    out.append('')
    out.append('impl Default for Globals {')
    out.append('    fn default() -> Self {')
    out.append('        Globals {')
    out += init
    out.append('        }')
    out.append('    }')
    out.append('}')
    out.append('')
    # --- JSON snapshot by original address (bridge to the emulator harness, tools/emu/game.py)
    out.append('impl Globals {')
    out.append('    /// First non-finite floating cell, with its original BASIC name and subscripts.')
    out.append('    pub fn first_nonfinite(&self) -> Option<String> {')
    for kind, a, name, t, bounds, desc in fields:
        if t not in ('EXT', 'DOUBLE', 'SINGLE'):
            continue
        f = snake(name)
        if kind == 'scalar':
            out.append('        if !self.%s.is_finite() { return Some("%s".into()); }' % (f, name))
        else:
            out.append('        if let Some(index) = self.%s.as_slice().iter().position(|v| !v.is_finite()) {' % f)
            if len(bounds) == 1:
                out.append('            return Some(format!("%s({})", index as i32 + %d));' % (name, bounds[0][0]))
            else:
                width = bounds[0][1] - bounds[0][0] + 1
                out.append('            return Some(format!("%s({}, {})", (index %% %d) as i32 + %d, (index / %d) as i32 + %d));' % (name, width, bounds[0][0], width, bounds[1][0]))
            out.append('        }')
    out.append('        None')
    out.append('    }')
    out.append('')
    out.append('    /// Snapshot as JSON keyed by original address: `{"6c41d0": [..], "6c3be0": 5, ..}`.')
    out.append('    /// Strings are JSON strings with one char per byte (U+0000..U+00FF); arrays are flat lists in')
    out.append('    /// PB storage order (first subscript fastest); CURRENCY is the raw scaled integer.')
    out.append('    pub fn to_json(&self) -> String {')
    out.append('        self.write_json(crate::snapshot::Writer::default())')
    out.append('    }')
    out.append('')
    out.append('    /// Approximate numeric JSON for presentation; use `to_json` for lossless checkpoints.')
    out.append('    pub fn to_json_portable(&self) -> String {')
    out.append('        self.write_json(crate::snapshot::Writer::portable())')
    out.append('    }')
    out.append('')
    out.append('    fn write_json(&self, mut w: crate::snapshot::Writer) -> String {')
    for kind, a, name, t, bounds, desc in fields:
        f = snake(name)
        if kind == 'array':
            out.append('        w.%s("%s", &self.%s);' % ('arr1' if len(bounds) == 1 else 'arr2', a, f))
        else:
            out.append('        w.val("%s", &self.%s);' % (a, f))
    out.append('        w.finish()')
    out.append('    }')
    out.append('')
    out.append('    /// Load a snapshot written by [`Globals::to_json`] or the emulator harness. Keys that are missing')
    out.append('    /// keep their current value.')
    out.append('    pub fn from_json(&mut self, s: &str) -> Result<(), String> {')
    out.append('        let r = crate::snapshot::Reader::parse(s)?;')
    for kind, a, name, t, bounds, desc in fields:
        f = snake(name)
        if kind == 'array':
            out.append('        r.%s("%s", &mut self.%s)?;' % ('arr1' if len(bounds) == 1 else 'arr2', a, f))
        else:
            out.append('        r.val("%s", &mut self.%s)?;' % (a, f))
    out.append('        Ok(())')
    out.append('    }')
    out.append('}')
    out.append('')
    out.append('/// (original name, address, PB type) of every field, in address order.')
    out.append('pub const GLOBALS: &[(&str, u32, &str)] = &[')
    for kind, a, name, t, bounds, desc in fields:
        out.append('    ("%s", 0x%s, "%s"),' % (name, a, t if kind == 'scalar' else t + '()'))
    out.append('];')
    p = os.path.join(ROOT, 'engine', 'wsr-core', 'src', 'state.rs')
    open(p, 'w').write('\n'.join(out) + '\n')
    print('%d fields (%d arrays), %d high halves folded into their wide value -> %s' % (
        len(fields), sum(1 for f in fields if f[0] == 'array'), len(skipped), p))
    for a, n in skipped:
        print('  folded', a, n)


if __name__ == '__main__':
    main()
